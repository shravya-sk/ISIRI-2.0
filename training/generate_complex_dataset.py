def generate_dataset():
    all_categories = [
        ("weather", WEATHER_PAIRS),
        ("youtube", YOUTUBE_PAIRS),
        ("spotify", SPOTIFY_PAIRS),
        ("google_search", GOOGLE_SEARCH_PAIRS),
        ("system", SYSTEM_PAIRS),
        ("browser", BROWSER_PAIRS),
        ("alarm", ALARM_PAIRS),
        ("hardware", HARDWARE_PAIRS),
        ("calculator", CALCULATOR_PAIRS),
        ("knowledge", KNOWLEDGE_PAIRS),
    ]

    records = []
    for intent_name, pairs in all_categories:
        for idx, (en, tu) in enumerate(pairs):
            if idx < 30:
                complexity = "short"
            elif idx < 60:
                complexity = "medium"
            else:
                complexity = "complex"

            records.append(
                {
                    "English": en.strip(),
                    "Tulu": tu.strip(),
                    "Intent": intent_name,
                    "Complexity": complexity,
                }
            )

    df_complex = pd.DataFrame(records)
    print(f"Generated {len(df_complex)} structured domain pairs.")
    print("Breakdown by complexity:")
    print(df_complex["Complexity"].value_counts())
    print("\nBreakdown by intent:")
    print(df_complex["Intent"].value_counts())

    df_complex.to_csv(OUTPUT_COMPLEX_CSV, index=False, encoding="utf-8")
    print(f"\nSaved 1,000 complex pairs to: {OUTPUT_COMPLEX_CSV}")

    # Merge with clean_dataset.csv
    if CLEAN_DATASET.exists():
        df_clean = pd.read_csv(CLEAN_DATASET)
        df_clean = df_clean[["English", "Tulu"]].dropna()

        # Combine
        df_expanded = pd.concat([df_clean, df_complex[["English", "Tulu"]]], ignore_index=True)

        # Deduplicate on normalized English key
        df_expanded["norm_en"] = (
            df_expanded["English"]
            .str.lower()
            .str.replace(r"\s+", " ", regex=True)
            .str.replace(r"[^\w\s]", "", regex=True)
            .str.strip()
        )

        before_dedup = len(df_expanded)
        df_expanded = df_expanded.drop_duplicates(subset=["norm_en"], keep="first")
        df_expanded = df_expanded.drop(columns=["norm_en"])

        print(f"\nMerging with clean_dataset.csv ({len(df_clean)} rows)...")
        print(f"Total after merge & deduplication: {len(df_expanded)} rows (was {before_dedup})")

        df_expanded.to_csv(OUTPUT_EXPANDED_CSV, index=False, encoding="utf-8")
        print(f"Saved expanded clean dataset to: {OUTPUT_EXPANDED_CSV}")

        # Also overwrite clean_dataset.csv so training scripts can directly use the full corpus
        df_expanded.to_csv(CLEAN_DATASET, index=False, encoding="utf-8")
        print(f"Updated primary dataset: {CLEAN_DATASET}")


if __name__ == "__main__":
    generate_dataset()
